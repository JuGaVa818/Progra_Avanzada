BEGIN;

CREATE TABLE IF NOT EXISTS "PRQ_Automoviles" (
    id integer GENERATED BY DEFAULT AS IDENTITY,
    color varchar(40) NOT NULL,
    anio smallint NOT NULL,
    fabricante varchar(80) NOT NULL,
    tipo varchar(20) NOT NULL,
    CONSTRAINT "PK_PRQ_Automoviles" PRIMARY KEY (id),
    CONSTRAINT "CK_PRQ_Automoviles_anio" CHECK (anio BETWEEN 1886 AND 2100),
    CONSTRAINT "CK_PRQ_Automoviles_tipo" CHECK (tipo IN ('sedán', '4x4', 'moto'))
);

CREATE TABLE IF NOT EXISTS "PRQ_Parqueo" (
    id integer GENERATED BY DEFAULT AS IDENTITY,
    nombre_provincia varchar(80) NOT NULL,
    nombre varchar(120) NOT NULL,
    precio_por_hora numeric(10, 2) NOT NULL,
    CONSTRAINT "PK_PRQ_Parqueo" PRIMARY KEY (id),
    CONSTRAINT "CK_PRQ_Parqueo_precio_por_hora" CHECK (precio_por_hora >= 0)
);

CREATE TABLE IF NOT EXISTS "PRQ_Ingreso_Automoviles" (
    consecutivo integer GENERATED BY DEFAULT AS IDENTITY,
    id_parqueo integer NOT NULL,
    id_automovil integer NOT NULL,
    fecha_hora_entrada timestamp without time zone NOT NULL,
    fecha_hora_salida timestamp without time zone,
    CONSTRAINT "PK_PRQ_Ingreso_Automoviles" PRIMARY KEY (consecutivo),
    CONSTRAINT "FK_PRQ_Ingreso_Automoviles_PRQ_Parqueo"
        FOREIGN KEY (id_parqueo) REFERENCES "PRQ_Parqueo" (id),
    CONSTRAINT "FK_PRQ_Ingreso_Automoviles_PRQ_Automoviles"
        FOREIGN KEY (id_automovil) REFERENCES "PRQ_Automoviles" (id),
    CONSTRAINT "CK_PRQ_Ingreso_Automoviles_fechas"
        CHECK (fecha_hora_salida IS NULL OR fecha_hora_salida >= fecha_hora_entrada)
);

CREATE INDEX IF NOT EXISTS "IX_PRQ_Ingreso_Automoviles_id_parqueo"
    ON "PRQ_Ingreso_Automoviles" (id_parqueo);
CREATE INDEX IF NOT EXISTS "IX_PRQ_Ingreso_Automoviles_id_automovil"
    ON "PRQ_Ingreso_Automoviles" (id_automovil);
CREATE INDEX IF NOT EXISTS "IX_PRQ_Ingreso_Automoviles_fecha_hora_entrada"
    ON "PRQ_Ingreso_Automoviles" (fecha_hora_entrada);

COMMIT;
